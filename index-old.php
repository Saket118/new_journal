            const track = document.getElementById("scrollingCardTrack");

            if (!track || track.children.length <= 3) return;

            track.innerHTML += track.innerHTML;

            let pause = false;

            setInterval(() => {
                if (pause) return;

                track.scrollLeft++;

                if (track.scrollLeft >= track.scrollWidth / 2) {
                    track.scrollLeft = 0;
                }
            }, 13);

            track.addEventListener("mouseenter", () => pause = true);
            track.addEventListener("mouseleave", () => pause = false);
        });
